def build_context(chunks: list[RetrievedChunk]) -> str:
    parts = [
        f'<chunk id="{i}" pages="{rc.chunk.pages_label}">\n{escape(rc.chunk.text, quote=False)}'
        "\n</chunk>"
        for i, rc in enumerate(chunks, start=1)
    ]
    return "<context>\n" + "\n".join(parts) + "\n</context>"


def build_user_message(question: str, chunks: list[RetrievedChunk]) -> str:
    return f"{build_context(chunks)}\n\nВопрос: {question}"


def build_condense_message(history: list[tuple[str, str]], question: str) -> str:
    names = {"user": "Пользователь", "assistant": "Ассистент"}
    lines = [f"{names.get(role, role)}: {text}" for role, text in history]
    return "История диалога:\n" + "\n".join(lines) + f"\n\nПоследний вопрос: {question}"


_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")


def no_answer_text(question: str) -> str:
    return NO_ANSWER_RU if _CYRILLIC.search(question) else NO_ANSWER_EN
